"""Train the Sketch Duel CNN on a subset of Google's Quick, Draw! dataset.

Usage:
    python training/train.py --data DIR --out model.js
DIR holds one <category>.npy (or .part) file per class, downloaded from
https://storage.googleapis.com/quickdraw_dataset/full/numpy_bitmap/<category>.npy
(a byte range covering the first N rows is enough; see README.md).
The result is a JS file that the browser game loads directly.
"""
import argparse, base64, json, math, os
import numpy as np
import torch, torch.nn as nn, torch.nn.functional as F

CLASSES = ["cat", "fish", "house", "tree", "sun", "star", "car", "bicycle",
           "apple", "banana", "umbrella", "clock", "cup", "flower", "bird",
           "guitar", "airplane", "pizza", "snowman", "rainbow", "butterfly",
           "eyeglasses", "moon", "key"]


class SketchCNN(nn.Module):
    def __init__(self, n):
        super().__init__()
        self.c1 = nn.Conv2d(1, 32, 3, padding=1)
        self.c2 = nn.Conv2d(32, 64, 3, padding=1)
        self.c3 = nn.Conv2d(64, 128, 3, padding=1)
        self.f1 = nn.Linear(128 * 3 * 3, 128)
        self.f2 = nn.Linear(128, n)
        self.drop = nn.Dropout(0.3)

    def forward(self, x):
        x = F.max_pool2d(F.relu(self.c1(x)), 2)  # 14
        x = F.max_pool2d(F.relu(self.c2(x)), 2)  # 7
        x = F.max_pool2d(F.relu(self.c3(x)), 2)  # 3
        x = self.drop(F.relu(self.f1(x.flatten(1))))
        return self.f2(x)


def load(data_dir, per_class):
    xs, ys = [], []
    for i, c in enumerate(CLASSES):
        path = next(p for p in (os.path.join(data_dir, c + ext) for ext in (".npy", ".part")) if os.path.exists(p))
        raw = open(path, "rb").read()
        hlen = int.from_bytes(raw[8:10], "little") + 10  # npy v1 header
        a = np.frombuffer(raw[hlen:], dtype=np.uint8)
        a = a[: (len(a) // 784) * 784].reshape(-1, 784)[:per_class]
        xs.append(a); ys.append(np.full(len(a), i))
    return np.concatenate(xs), np.concatenate(ys)


def center(x):
    """Re-centre each bitmap on its bounding box, like the browser does."""
    out = torch.zeros_like(x)
    for k in range(x.shape[0]):
        im = x[k, 0]
        r = (im > 0.05).any(1).nonzero(); c = (im > 0.05).any(0).nonzero()
        if len(r) == 0: continue
        r0, r1, c0, c1 = r[0].item(), r[-1].item(), c[0].item(), c[-1].item()
        h, w = r1 - r0 + 1, c1 - c0 + 1
        t, l = (28 - h) // 2, (28 - w) // 2
        out[k, 0, t:t + h, l:l + w] = im[r0:r1 + 1, c0:c1 + 1]
    return out


def augment(x):
    n = x.shape[0]
    ang = (torch.rand(n) - 0.5) * math.radians(24)
    s = 0.85 + torch.rand(n) * 0.3
    tx, ty = (torch.rand(n) - 0.5) * 0.2, (torch.rand(n) - 0.5) * 0.2
    cos, sin = torch.cos(ang) / s, torch.sin(ang) / s
    theta = torch.stack([torch.stack([cos, -sin, tx], 1), torch.stack([sin, cos, ty], 1)], 1)
    grid = F.affine_grid(theta, x.shape, align_corners=False)
    return F.grid_sample(x, grid, align_corners=False, padding_mode="zeros")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", default="model.js")
    ap.add_argument("--per-class", type=int, default=12000)
    ap.add_argument("--epochs", type=int, default=6)
    a = ap.parse_args()
    torch.manual_seed(0); np.random.seed(0)

    X, Y = load(a.data, a.per_class)
    X = center(torch.tensor(X, dtype=torch.float32).view(-1, 1, 28, 28) / 255.0)
    Y = torch.tensor(Y)
    perm = torch.randperm(len(X)); X, Y = X[perm], Y[perm]
    nval = len(X) // 10
    Xv, Yv, Xt, Yt = X[:nval], Y[:nval], X[nval:], Y[nval:]
    print(f"train {len(Xt)}  val {len(Xv)}  classes {len(CLASSES)}")

    m = SketchCNN(len(CLASSES))
    opt = torch.optim.AdamW(m.parameters(), 2e-3, weight_decay=1e-4)
    steps = a.epochs * math.ceil(len(Xt) / 256)
    sched = torch.optim.lr_scheduler.OneCycleLR(opt, 3e-3, total_steps=steps)
    for ep in range(a.epochs):
        m.train(); p = torch.randperm(len(Xt))
        for i in range(0, len(Xt), 256):
            idx = p[i:i + 256]
            loss = F.cross_entropy(m(augment(Xt[idx])), Yt[idx], label_smoothing=0.05)
            opt.zero_grad(); loss.backward(); opt.step(); sched.step()
        m.eval()
        with torch.no_grad():
            acc = sum((m(Xv[i:i + 1024]).argmax(1) == Yv[i:i + 1024]).sum().item() for i in range(0, nval, 1024)) / nval
        print(f"epoch {ep + 1}: loss {loss.item():.3f}  val acc {acc:.4f}", flush=True)

    layers = {}
    for k, v in m.state_dict().items():
        arr = v.detach().numpy().astype("<f4")
        layers[k] = {"shape": list(arr.shape), "data": base64.b64encode(arr.tobytes()).decode()}
    meta = {"classes": CLASSES, "valAccuracy": round(acc, 4), "layers": layers}
    with open(a.out, "w") as f:
        f.write("// Generated by training/train.py: CNN weights trained on Quick, Draw! bitmaps.\n")
        f.write("window.SKETCH_MODEL = " + json.dumps(meta) + ";\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
